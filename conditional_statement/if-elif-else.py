marks=float(input("Enter your score:"))

if marks>=90:
    print("Grade A+")

elif marks>=85:
    print("Grade A")

elif marks>=80:
    print("Grade B+")

elif marks>=75:
    print("Grade B")

elif marks>=70:
    print("Grade C+")

elif marks>=65:
    print("Grade C")

elif marks>=55:
    print("Grade D+")

else:
    print("You Failed")    
