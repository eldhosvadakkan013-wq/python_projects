#3.remove() delete cheyaan
'''vehicles=["Bike","Car","Bus"]
vehicles.remove("Car")
print(vehicles)'''

#4.pop() last element automatically delete aakum
'''fruits=["Apple","Banana","Citrus"]
fruits.pop()
print(fruits)'''

#5.sort() arrange cheyaan
'''numbers=[5,6,4,8,3,1,2,7]
numbers.sort()
print(numbers)'''

#6.reverse()reverse cheyth varaan
'''fruits=["Apple","Banana","Citrus"]
fruits.reverse()
print(fruits)'''

